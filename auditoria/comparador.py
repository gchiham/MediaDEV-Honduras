def _cargar(nombre, ruta):
    spec = importlib.util.spec_from_file_location(nombre, ruta)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


_reglas = _cargar("reglas_mediacap", AQUI / "reglas_mediacap.py")
_inv = _cargar("mediacap_inventario", AQUI / "recolector" / "mediacap_inventario.py")
hallazgo, a_markdown, redactar = _reglas.hallazgo, _reglas.a_markdown, _inv.redactar

UNITS_DIR = "/etc/systemd/system/"
# Dónde se versiona cada unit/drop-in de /etc/systemd/system: (repo, prefijo). Se busca en orden.
FUENTES_UNITS = [("infra", "mediacap/systemd/"), ("captura", "agente/systemd/"),
                 ("captura", "auditoria/recolector/instalar/")]
CRON = {"/var/spool/cron/crontabs/root": "mediacap/cron/root.crontab",
        "/etc/cron.d/tvprem-watch": "mediacap/cron/tvprem-watch"}
# Cabecera que agrega `crontab` al instalar; no es parte del contenido versionado.
_CABECERA_CRON = re.compile(r"\A(# DO NOT EDIT THIS FILE.*\n# \(.*\n# \(Cron version.*\n)")
DESTROYER_PREFIJO = "cap/"
MAX_EDAD_INVENTARIO_H = 7
DISCO_MIN_LIBRE_PCT = 15
REINICIOS_ALTOS = 5
PROPIA = "mediacap-auditor-inventario.service"   # se inventaría a sí misma mientras corre
# Archivos que deben ser 600. gateway.conf y las llaves públicas son 644 a propósito.
_SECRETO_ESTRICTO = re.compile(r"\.(env|key)$|^(?!.*public).*\.pem$")


class Repo:
    """Acceso de solo lectura a un clon en una ref fija."""

    def __init__(self, ruta, ref):
        self.ruta, self.ref = Path(ruta), ref
        self.sha = self._git("rev-parse", ref).strip()

    def _git(self, *args, binario=False):
        p = subprocess.run(["git", "-C", str(self.ruta), "--no-optional-locks", *args],
                           capture_output=True, timeout=60)
        if p.returncode != 0:
            raise FileNotFoundError(p.stderr.decode(errors="replace").strip())
        return p.stdout if binario else p.stdout.decode(errors="replace")

    def leer(self, ruta) -> bytes | None:
        try:
            return self._git("show", f"{self.ref}:{ruta}", binario=True)
        except FileNotFoundError:
            return None

    def listar(self, prefijo) -> list[str]:
        return self._git("ls-tree", "-r", "--name-only", self.ref, "--", prefijo).splitlines()

    def es_ancestro(self, sha) -> bool | None:
        """True si sha está en la historia de ref; None si el clon no conoce ese commit."""
        if subprocess.run(["git", "-C", str(self.ruta), "cat-file", "-e", f"{sha}^{{commit}}"],
                          capture_output=True).returncode != 0:
            return None
        return subprocess.run(["git", "-C", str(self.ruta), "merge-base", "--is-ancestor", sha, self.ref],
                              capture_output=True).returncode == 0

    def commits_entre(self, desde) -> int:
        return int(self._git("rev-list", "--count", f"{desde}..{self.ref}").strip() or 0)


def _sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def _txt(b: bytes) -> str:
    return redactar(b.decode(errors="replace"))


# ── comparaciones contra repos ───────────────────────────────────────────────

def comparar_git(inv, captura: Repo):
    out = []
    for g in inv.get("git") or []:
        loc = f"mediaCAP:{g['ruta']}"
        if g.get("error"):
            out.append(hallazgo("DR001", "POTENTIAL", "P2", loc, 0, "Repo desplegado sin git", g["error"],
                                "Ver si la copia perdió .git; sin git no se puede comparar por commit."))
            continue
        head, n = g["head"], len(g.get("cambios", []))
        anc = captura.es_ancestro(head)
        if head == captura.sha:
            pass
        elif anc is None:
            out.append(hallazgo(
                "DR002", "CONFIRMED", "P1", loc, 0, "Desplegado un commit que no está en GitHub",
                f"HEAD {head[:7]} no existe en {captura.ref} ({captura.sha[:7]}): cambios hechos en el server sin push.",
                "En mediaCAP: git log -3; subir esos commits o descartarlos."))
        elif anc:
            atras = captura.commits_entre(head)
            out.append(hallazgo(
                "DR003", "LIKELY", "P2", loc, 0, f"Desplegado {atras} commit(s) detrás de {captura.ref}",
                f"HEAD {head[:7]}, {captura.ref} {captura.sha[:7]}. Puede ser intencional (PR sin desplegar).",
                f"git log {head[:7]}..{captura.ref} --oneline: confirmar si algo de eso debía estar en prod."))
        else:
            out.append(hallazgo(
                "DR002", "CONFIRMED", "P1", loc, 0, "Desplegado un commit que divergió de GitHub",
                f"HEAD {head[:7]} existe pero no es ancestro de {captura.ref} ({captura.sha[:7]}).",
                "Reconciliar: rebase/merge del commit desplegado o volver a main."))
        for c in g.get("cambios", []):
            estado, ruta = c[:2], c[3:]
            out.append(hallazgo(
                "DR004", "CONFIRMED", "P1" if not estado.startswith("??") else "P3", f"{loc}/{ruta}", 0,
                "Archivo modificado en el server sin commit" if "?" not in estado
                else "Archivo sin versionar en el server",
                f"git status: '{estado}' (de {n} cambio(s) en total).",
                "En mediaCAP: git diff -- <archivo>; commitear vía PR o restaurar."))
    return out


def comparar_destroyer(inv, destroyer: Repo):
    out = []
    for raiz in inv.get("codigo_sin_git") or []:
        if not raiz.get("existe"):
            continue
        prod = {a["ruta"]: a for a in raiz["archivos"]}
        repo = {r[len(DESTROYER_PREFIJO):] for r in destroyer.listar(DESTROYER_PREFIJO)
                if Path(r).suffix in _inv.EXT_CODIGO and not _inv.PATRON_SECRETO.search(Path(r).name)}
        for rel in sorted(prod.keys() | repo):
            loc = f"mediaCAP:{raiz['raiz']}/{rel}"
            if rel not in repo:
                out.append(hallazgo(
                    "DR010", "POTENTIAL", "P2", loc, 0, "Código desplegado que no está en GitHub",
                    f"Existe en el server (mtime {prod[rel]['mtime_utc']}) y no en destroyer:{DESTROYER_PREFIJO}{rel}.",
                    "Ver si algún unit, cron o import lo usa; versionarlo o moverlo fuera."))
            elif rel not in prod:
                out.append(hallazgo(
                    "DR011", "POTENTIAL", "P3", loc, 0, "Está en GitHub pero no desplegado",
                    f"destroyer:{DESTROYER_PREFIJO}{rel} no existe en el server.",
                    "Confirmar si es de otro nodo/instalador o si faltó desplegarlo."))
            elif prod[rel]["sha256"] != _sha(destroyer.leer(DESTROYER_PREFIJO + rel) or b""):
                out.append(hallazgo(
                    "DR012", "CONFIRMED", "P1", loc, 0, "Código desplegado distinto a GitHub",
                    f"sha256 del server {(prod[rel]['sha256'] or 'sin hash')[:12]} ≠ "
                    f"destroyer@{destroyer.sha[:7]}; mtime server {prod[rel]['mtime_utc']}.",
                    "diff entre el archivo del server y el repo; decidir cuál es la verdad y sincronizar."))
    return out


def _buscar_unit(repos, nombre_rel):
    """nombre_rel: 'x.service' o 'x.service.d/y.conf'. Devuelve (etiqueta, bytes) o (None, None)."""
    for clave, prefijo in FUENTES_UNITS:
        r = repos.get(clave)
        if r is not None:
            datos = r.leer(prefijo + nombre_rel)
            if datos is not None:
                return f"{clave}:{prefijo}{nombre_rel}", datos
    return None, None


def _comparar_texto(loc, regla, etiqueta, prod, repo_bytes, que):
    """Hash igual = nada. Distinto pero igual tras redactar = solo cambian secretos (esperado)."""
    if prod["sha256"] == _sha(repo_bytes):
        return []
    if prod.get("texto") is not None and prod["texto"] == _txt(repo_bytes):
        return [hallazgo(regla, "FALSE_POSITIVE", "P3", loc, 0, f"{que} difiere solo en valores redactados",
                         f"Igual a {etiqueta} salvo secretos (el repo lleva placeholders).",
                         "Nada que hacer si el repo usa placeholders a propósito.")]
    return [hallazgo(regla, "CONFIRMED", "P1", loc, 0, f"{que} distinto a GitHub",
                     f"sha256 del server ≠ {etiqueta}; mtime server {prod['mtime_utc']}.",
                     "diff (redactado) entre el server y el repo; sincronizar en el sentido correcto.")]


def comparar_systemd(inv, repos):
    out, vistos = [], set()
    for u in inv.get("systemd") or []:
        for a in u.get("archivos", []):
            if not a["ruta"].startswith(UNITS_DIR):
                continue                        # unit de paquete (/usr/lib): no se versiona
            rel = a["ruta"][len(UNITS_DIR):]
            vistos.add(rel)
            loc = f"mediaCAP:{a['ruta']}"
            etiqueta, datos = _buscar_unit(repos, rel)
            if datos is None:
                out.append(hallazgo("DR020", "POTENTIAL", "P2", loc, 0, "Unit sin versionar",
                                    f"No está en {', '.join(p for _, p in FUENTES_UNITS)}.",
                                    "Agregarla a mediadev-infra/mediacap/systemd/ o documentar por qué no."))
            else:
                out += _comparar_texto(loc, "DR021", etiqueta, a, datos, "Unit")
    infra = repos.get("infra")
    if infra is not None:
        for r in infra.listar("mediacap/systemd/"):
            rel = r[len("mediacap/systemd/"):]
            if rel not in vistos:
                out.append(hallazgo(
                    "DR022", "POTENTIAL", "P3", f"infra:{r}", 0, "Unit versionada que no está activa en mediaCAP",
                    "Está en mediadev-infra pero el inventario no la encontró en /etc/systemd/system.",
                    "Ver si se retiró (borrarla del repo) o si falta instalarla."))
    return out


def comparar_cron(inv, infra: Repo):
    out = []
    prod = {c["ruta"]: c for c in inv.get("cron") or []}
    for ruta, rel in CRON.items():
        loc = f"mediaCAP:{ruta}"
        datos = infra.leer(rel)
        if ruta not in prod and datos is None:
            continue                            # ni en el server ni en el repo: nada que comparar
        if ruta not in prod:
            out.append(hallazgo("DR031", "POTENTIAL", "P2", loc, 0, "Cron versionado que no está en el server",
                                f"infra:{rel} existe; {ruta} no.", "Ver si se retiró o falta instalarlo."))
        elif datos is None:
            out.append(hallazgo("DR030", "POTENTIAL", "P2", loc, 0, "Cron sin versionar",
                                f"No está infra:{rel}.", "Versionarlo en mediadev-infra/mediacap/cron/."))
        else:
            c = dict(prod[ruta])
            c["texto"] = _CABECERA_CRON.sub("", c.get("texto") or "")
            sin_cab = _CABECERA_CRON.sub("", _txt(datos))
            if c["texto"] == sin_cab and c["sha256"] != _sha(datos):
                continue                        # solo difiere la cabecera de `crontab`
            out += _comparar_texto(loc, "DR032", f"infra:{rel}", c, datos, "Crontab")
    return out


