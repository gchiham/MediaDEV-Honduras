import hashlib
import importlib.util
import shutil
import subprocess
import tempfile
import time
import unittest
from pathlib import Path

RAIZ = Path(__file__).resolve().parents[1]
_SPEC = importlib.util.spec_from_file_location("comparador", RAIZ / "auditoria" / "comparador.py")
cmp = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(cmp)

UNIT = "[Service]\nExecStart=/usr/bin/python3 /opt/media-ai/daemon/stream_daemon.py\n"
DROPIN = "[Service]\nEnvironment=TG_TOKEN=PLACEHOLDER\n"
CRON_REPO = "0 */2 * * * find /var/www/streams -mmin +120 -delete\n"
CRON_CAB = ("# DO NOT EDIT THIS FILE - edit the master and reinstall.\n"
            "# (/tmp/crontab.x installed on Mon Jun 14 09:36:00 2026)\n"
            "# (Cron version -- $Id: crontab.c,v 2.13 1994/01/17 03:20:37 vixie Exp $)\n")


def sha(t):
    return hashlib.sha256(t.encode() if isinstance(t, str) else t).hexdigest()


def git(repo, *args):
    return subprocess.run(["git", "-C", str(repo), "-c", "user.email=t@t", "-c", "user.name=t", *args],
                          check=True, capture_output=True, text=True).stdout.strip()


def crear_repo(base, nombre, archivos):
    r = base / nombre
    r.mkdir()
    git(r, "init", "-q", "-b", "main")
    for rel, txt in archivos.items():
        (r / rel).parent.mkdir(parents=True, exist_ok=True)
        (r / rel).write_text(txt)
    git(r, "add", "-A")
    git(r, "commit", "-qm", "inicial")
    return r


def unit(nombre, texto, ruta=None, **props):
    ruta = ruta or f"/etc/systemd/system/{nombre}"
    return {"unidad": nombre, "ActiveState": "active", "NRestarts": "0", **props,
            "archivos": [{"ruta": ruta, "sha256": sha(texto), "texto": cmp.redactar(texto),
                          "mtime_utc": "2026-10-01T00:00:00Z"}]}


@unittest.skipUnless(shutil.which("git"), "requiere git")
class Comparador(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.captura = crear_repo(self.tmp, "captura", {"daemon/stream_daemon.py": "x\n"})
        self.destroyer = crear_repo(self.tmp, "destroyer", {"cap/watchdog.py": "w\n",
                                                            "cap/gateway/engine/api.py": "a\n"})
        self.infra = crear_repo(self.tmp, "infra", {
            "mediacap/systemd/stream-daemon.service": UNIT,
            "mediacap/systemd/mediadev-monitor.service.d/tg-env.conf": DROPIN,
            "mediacap/cron/root.crontab": CRON_REPO})
        self.head = git(self.captura, "rev-parse", "HEAD")

    def repos(self):
        return {k: cmp.Repo(getattr(self, k), "main") for k in ("captura", "destroyer", "infra")}

    def inventario(self, **cambios):
        inv = {
            "version": 1, "generado_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "errores": {},
            "git": [{"ruta": "/opt/media-ai", "head": self.head, "rama": "main", "cambios": []}],
            "codigo_sin_git": [{"raiz": "/opt/destroyer", "existe": True, "truncado": False, "archivos": [
                {"ruta": "watchdog.py", "sha256": sha("w\n"), "mtime_utc": "x"},
                {"ruta": "gateway/engine/api.py", "sha256": sha("a\n"), "mtime_utc": "x"}]}],
            "systemd": [unit("stream-daemon.service", UNIT),
                        unit("mediadev-monitor.service.d", "[Service]\nEnvironment=TG_TOKEN=5955525376:"
                             + "A" * 35 + "\n", ruta="/etc/systemd/system/mediadev-monitor.service.d/tg-env.conf"),
                        unit("nginx.service", "[Service]\n", ruta="/usr/lib/systemd/system/nginx.service")],
            "cron": [{"ruta": "/var/spool/cron/crontabs/root", "sha256": sha(CRON_CAB + CRON_REPO),
                      "texto": cmp.redactar(CRON_CAB + CRON_REPO), "mtime_utc": "x"}],
            "secretos_meta": [{"ruta": "/etc/mediadev-db.env", "modo": "600", "dueno": "root", "grupo": "root"},
                              {"ruta": "/etc/mediadev/cf_public.pem", "modo": "644", "dueno": "root", "grupo": "root"},
                              {"ruta": "/etc/mediadev/gateway.conf", "modo": "644", "dueno": "root", "grupo": "root"}],
            "procesos": {"ffmpeg": 17, "ffmpeg_ppid1": 0},
            "disco": {"df": [{"ruta": "/", "libre_gb": 60.0, "total_gb": 80.0}]},
            "venvs": [{"ruta": "/opt/media-ai/monitor/venv", "paquetes": []}],
        }
        inv["systemd"][1]["archivos"][0]["texto"] = cmp.redactar(
            "[Service]\nEnvironment=TG_TOKEN=5955525376:" + "A" * 35 + "\n")
        inv["systemd"].append(unit("mediadev-monitor.service",
                                   "ExecStart=/opt/media-ai/monitor/venv/bin/python3 m.py\n",
                                   ruta="/usr/lib/systemd/system/mediadev-monitor.service"))
        for k, v in cambios.items():
            inv[k] = v
        return inv

    def reglas(self, hs, estado=None):
        return sorted(h["regla"] for h in hs if estado is None or h["estado"] == estado)

    def test_todo_sincronizado_no_reporta_drift(self):
        hs = cmp.comparar(self.inventario(), self.repos())
        # El drop-in difiere solo en el token (repo con placeholder): se informa como FALSE_POSITIVE.
        self.assertEqual([(h["regla"], h["estado"]) for h in hs], [("DR021", "FALSE_POSITIVE")])

    def test_archivo_modificado_en_el_server(self):
        inv = self.inventario()
        inv["git"][0]["cambios"] = [" M daemon/stream_daemon.py", "?? scripts/parche.py"]
        hs = [h for h in cmp.comparar(inv, self.repos()) if h["regla"] == "DR004"]
        self.assertEqual([(h["estado"], h["severidad"]) for h in hs], [("CONFIRMED", "P1"), ("CONFIRMED", "P3")])

    def test_desplegado_atras_de_main(self):
        (self.captura / "nuevo.py").write_text("n\n")
        git(self.captura, "add", "-A")
        git(self.captura, "commit", "-qm", "nuevo")
        hs = cmp.comparar(self.inventario(), self.repos())
        dr3 = [h for h in hs if h["regla"] == "DR003"]
        self.assertEqual(len(dr3), 1)
        self.assertIn("1 commit", dr3[0]["titulo"])
        self.assertEqual(dr3[0]["estado"], "LIKELY")

    def test_commit_desplegado_que_no_esta_en_github(self):
        inv = self.inventario()
        inv["git"][0]["head"] = "f" * 40
        self.assertIn("DR002", self.reglas(cmp.comparar(inv, self.repos()), "CONFIRMED"))

    def test_destroyer_distinto_faltante_y_sobrante(self):
        inv = self.inventario()
        arch = inv["codigo_sin_git"][0]["archivos"]
        arch[0]["sha256"] = sha("w modificado en prod\n")
        arch.pop(1)
        arch.append({"ruta": "launch_eval.py", "sha256": sha("l\n"), "mtime_utc": "x"})
        hs = cmp.comparar(inv, self.repos())
        self.assertEqual(self.reglas([h for h in hs if h["regla"].startswith("DR01")]),
                         ["DR010", "DR011", "DR012"])
        self.assertEqual(next(h for h in hs if h["regla"] == "DR012")["estado"], "CONFIRMED")

    def test_unit_distinta_sin_versionar_y_retirada(self):
        inv = self.inventario()
        inv["systemd"][0] = unit("stream-daemon.service", UNIT + "Nice=5\n")
        inv["systemd"].append(unit("mediadev-nueva.service", "[Service]\nExecStart=/bin/true\n"))
        git(self.infra, "rm", "-q", "mediacap/cron/root.crontab")
        (self.infra / "mediacap/systemd/vpc-peering.service").write_text("[Unit]\n")
        git(self.infra, "add", "-A")
        git(self.infra, "commit", "-qm", "x")
        hs = cmp.comparar(inv, self.repos())
        self.assertIn("DR021", self.reglas(hs, "CONFIRMED"))
        self.assertIn("DR020", self.reglas(hs, "POTENTIAL"))
        self.assertIn("DR022", self.reglas(hs, "POTENTIAL"))
        self.assertIn("DR030", self.reglas(hs))                 # crontab ya no versionado

    def test_units_de_paquete_no_se_comparan(self):
        hs = cmp.comparar(self.inventario(), self.repos())
        self.assertFalse(any("nginx" in h["archivo"] for h in hs))

    def test_unit_versionada_en_otro_repo_se_encuentra(self):
        (self.captura / "agente/systemd").mkdir(parents=True)
        (self.captura / "agente/systemd/mediacap-vigia-vista.timer").write_text("[Timer]\n")
        git(self.captura, "add", "-A")
        git(self.captura, "commit", "-qm", "v")
        inv = self.inventario()
        inv["git"][0]["head"] = git(self.captura, "rev-parse", "HEAD")
        inv["systemd"].append(unit("mediacap-vigia-vista.timer", "[Timer]\n"))
        self.assertFalse([h for h in cmp.comparar(inv, self.repos()) if "vigia" in h["archivo"]])

    def test_cron_distinto(self):
        inv = self.inventario()
        inv["cron"][0].update(sha256=sha(CRON_CAB + CRON_REPO + "* * * * * x\n"),
                              texto=cmp.redactar(CRON_CAB + CRON_REPO + "* * * * * x\n"))
        self.assertIn("DR032", self.reglas(cmp.comparar(inv, self.repos()), "CONFIRMED"))

    def test_chequeos_de_inventario(self):
        inv = self.inventario(
            generado_utc="2026-01-01T00:00:00Z", errores={"disco": "TimeoutExpired"},
            procesos={"ffmpeg": 20, "ffmpeg_ppid1": 3},
            disco={"df": [{"ruta": "/", "libre_gb": 5.0, "total_gb": 80.0}]},
            venvs=[{"ruta": "/opt/medio-ai/venv", "paquetes": ["x"]},
                   {"ruta": "/opt/media-ai/monitor/venv", "paquetes": []}])
        inv["secretos_meta"].append({"ruta": "/etc/mediadev-s3.env", "modo": "644", "dueno": "root", "grupo": "root"})
        inv["systemd"].append(unit("video-segment-uploader.service", "[Service]\n", ActiveState="failed"))
        inv["systemd"].append(unit("mediadev-logs.service", "[Service]\n", NRestarts="12"))
        hs = cmp.chequear_inventario(inv)
        self.assertEqual(self.reglas(hs), ["IN001", "IN002", "IN010", "IN011", "IN020", "IN030", "IN031", "IN040"])
        self.assertEqual(next(h for h in hs if h["regla"] == "IN020")["archivo"], "mediaCAP:/etc/mediadev-s3.env")
        self.assertEqual(next(h for h in hs if h["regla"] == "IN040")["archivo"], "mediaCAP:/opt/medio-ai/venv")

    def test_llaves_publicas_y_gateway_conf_no_son_secretos(self):
        hs = cmp.chequear_inventario(self.inventario())
        self.assertNotIn("IN020", self.reglas(hs))

    def test_su_propia_unit_activating_no_alarma(self):
        inv = self.inventario()
        inv["systemd"].append(unit(cmp.PROPIA, "[Service]\n", ActiveState="failed"))
        self.assertNotIn("IN030", self.reglas(cmp.chequear_inventario(inv)))

    def test_no_modifica_los_repos(self):
        def huella(r):
            return sorted((p.relative_to(r).as_posix(), p.stat().st_mtime_ns)
                          for p in r.rglob("*") if p.is_file())
        antes = {k: huella(getattr(self, k)) for k in ("captura", "destroyer", "infra")}
        inv = self.inventario()
        inv["git"][0]["cambios"] = [" M daemon/stream_daemon.py"]
        cmp.comparar(inv, self.repos())
        self.assertEqual({k: huella(getattr(self, k)) for k in antes}, antes)

    def test_hallazgos_con_evidencia_y_como_confirmar(self):
        inv = self.inventario()
        inv["git"][0]["head"] = "f" * 40
        for h in cmp.comparar(inv, self.repos()):
            self.assertTrue(h["evidencia"] and h["como_confirmar"], h)
            self.assertIn(h["estado"], ("CONFIRMED", "LIKELY", "POTENTIAL", "FALSE_POSITIVE"))


if __name__ == "__main__":
    unittest.main()
